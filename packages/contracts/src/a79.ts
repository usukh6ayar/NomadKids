// ── The progress record (2026-10-08, the client) ─────────────────────────────
//
// A teacher links an observation to one or more А/79 criteria and says how the
// skill showed; «Үр дүнгийн үнэлгээ» reads a child's criteria back as a result.
//
//   PUT /observations/:observationId/a79-links      ← observationA79LinksSchema
//   GET /children/:childId/a79-progress?level=I…IV  → a79ProgressSchema
//   GET /groups/:groupId/a79-summary?from=&to=      → a79GroupSummarySchema
//
// ★ Moved here from the web app (2026-10-16) so the server scores a criterion
// with the same list and the same rule the screens draw.

export const A79_LEVEL_KEYS = ["I", "II", "III", "IV"] as const;
export type A79LevelKey = (typeof A79_LEVEL_KEYS)[number];

export const A79_DOMAINS = ["Мэдлэг", "Чадвар", "Төлөвшил"] as const satisfies readonly A79Domain[];

/** How the skill showed — the four the client's design names. */
export const A79_STATUSES = ["INDEPENDENT", "SUPPORTED", "DEVELOPING", "NOT_YET"] as const;
export type A79Status = (typeof A79_STATUSES)[number];

export function a79Level(key: A79LevelKey): A79Level {
  return A79_LEVELS.find((level) => level.key === key)!;
}

/** The level a child's age puts them at — 2→I, 3→II, 4→III, 5→IV, clamped. */
export function a79LevelForAge(years: number | null): A79LevelKey {
  if (years === null) return "I";
  return A79_LEVEL_KEYS[Math.min(3, Math.max(0, years - 2))]!;
}

/**
 * ★ A criterion counts as met only when its latest evidence is «Бие даан».
 * А/79 marks each criterion 0 or 1; «Дэмжлэгтэй» is a skill on its way, not
 * yet one the child has.
 */
export function a79IsMet(status: A79Status): boolean {
  return status === "INDEPENDENT";
}

export const a79LinkSchema = z
  .object({
    level: z.enum(A79_LEVEL_KEYS),
    number: z.number().int().min(1),
    status: z.enum(A79_STATUSES),
    note: z.string().trim().max(500).nullish(),
  })
  .strict()
  .refine((link) => link.number <= a79Level(link.level).criteria.length, {
    message: "А/79-д ийм дугаартай шалгуур алга",
    path: ["number"],
  });
export type A79Link = z.infer<typeof a79LinkSchema>;

/** The note's whole set of links — a PUT replaces it. One link per criterion. */
export const observationA79LinksSchema = z
  .object({ links: z.array(a79LinkSchema).max(60) })
  .strict()
  .refine(
    ({ links }) => new Set(links.map((l) => `${l.level}-${l.number}`)).size === links.length,
    { message: "Нэг шалгуурыг хоёр удаа холбох боломжгүй", path: ["links"] },
  );
export type ObservationA79Links = z.infer<typeof observationA79LinksSchema>;

export const a79ProgressQuerySchema = z.object({ level: z.enum(A79_LEVEL_KEYS) });

/** One linked note, as evidence for one criterion. */
export const a79EvidenceSchema = z.object({
  observationId: z.string(),
  observedOn: z.string(),
  status: z.enum(A79_STATUSES),
  /** «Ажиглалт», «Ярилцлага», «Бүтээл» — the note's type name. */
  typeName: z.string().nullish(),
  /** The link's own «Тайлбар», else the opening of the note. */
  note: z.string().nullish(),
});
export type A79Evidence = z.infer<typeof a79EvidenceSchema>;

/**
 * A child's criteria at one level: the latest status the evidence gives each,
 * and every note linked to it, newest first. A criterion nobody has linked is
 * absent, not `NOT_YET` — the screen fills those in from the full list.
 */
export const a79ProgressSchema = z.object({
  level: z.enum(A79_LEVEL_KEYS),
  criteria: z.array(
    z.object({
      number: z.number().int(),
      status: z.enum(A79_STATUSES),
      evidence: z.array(a79EvidenceSchema),
    }),
  ),
});
export type A79Progress = z.infer<typeof a79ProgressSchema>;

export const a79SummaryQuerySchema = z
  .object({ from: z.iso.date().optional(), to: z.iso.date().optional() })
  .refine((q) => (q.from === undefined) === (q.to === undefined), {
    message: "Эхлэх, дуусах огноог хамт өгнө үү",
  })
  .refine((q) => !q.from || !q.to || q.from <= q.to, {
    message: "Эхлэх огноо нь дуусах огнооноос хойш байна",
  });
export type A79SummaryQuery = z.infer<typeof a79SummaryQuerySchema>;

/**
 * A group's А/79 result, one row per child — counts, not each child's criteria,
 * so the tab is one request and not one per child (CLAUDE.md §3.4).
 */
export const a79GroupSummarySchema = z.object({
  children: z.array(
    z.object({
      childId: z.string(),
      firstName: z.string(),
      lastName: z.string(),
      level: z.enum(A79_LEVEL_KEYS),
      /**
       * ★ A solo workspace's child whose family has not paid the portal fee
       * (CLAUDE.md §1.7) — named, as the roster is, with every figure withheld
       * (0 / 0, no parts). Until 2026-10-17 such a child was left out, and a
       * group of unpaid children read «Бүлэгт хүүхэд алга».
       */
      feeDue: z.boolean(),
      achieved: z.number().int(),
      total: z.number().int(),
      /**
       * ★ How many of the level's criteria any note is linked to (2026-10-27,
       * the user's director report: eighteen children «0% · Хөгжиж байна»).
       * 0 is a child nobody has linked a note for — not assessed, which is not
       * «Хөгжиж байна». Absent from an older server.
       */
      assessed: z.number().int().nullish(),
      byDomain: z.array(
        z.object({
          domain: z.enum(A79_DOMAINS),
          achieved: z.number().int(),
          total: z.number().int(),
        }),
      ),
    }),
  ),
});
export type A79GroupSummary = z.infer<typeof a79GroupSummarySchema>;
