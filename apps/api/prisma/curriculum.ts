/**
 * The Mongolian preschool curriculum's development indicators — СҮД.
 *
 * ★ Transcribed from the client's own spreadsheet, 2026-09-11, not invented.
 *
 * Seven strands, seventy-one indicators, each written out at up to four levels.
 * This is a national standard rather than kindergarten configuration, so it
 * ships as system rows the way `SYSTEM_DOMAINS` and `SYSTEM_LEVELS` do — a
 * kindergarten may add its own beside them but may not edit these.
 *
 * ★★ Two transcription faults in the source are corrected here rather than in
 * the reader, and both are recorded because the next import will meet them
 * again:
 *
 *  · The Cyrillic `б` is typed throughout as the digit `6` — "МАТ2.16" is
 *    "МАТ2.1б". Left alone it splits one indicator into two and leaves the
 *    other three levels looking empty.
 *  · One cell (`ХЯ3.б.`) lost its indicator number altogether. The row is the
 *    authority — one row is one indicator across four levels — so it takes the
 *    number its siblings agree on.
 *
 * ★★★ A level missing from an indicator is the source's own gap, not a
 * transcription loss: several strands begin at level II or III because the
 * behaviour does not exist earlier. Seeded as absent rather than blank, so a
 * screen can say "this indicator starts at III" instead of showing an empty
 * card.
 */

