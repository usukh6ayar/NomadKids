export interface A79Level {
  key: "I" | "II" | "III" | "IV";
  criteria: { domain: A79Domain; text: string }[];
}

function level(key: A79Level["key"], domains: Record<A79Domain, string[]>): A79Level {
  return {
    key,
    criteria: (Object.keys(domains) as A79Domain[]).flatMap((domain) =>
      domains[domain].map((text) => ({ domain, text })),
    ),
  };
}

